// Helper function to get color based on music features
export const getColorFromFeatures = (features: MusicMemory['features']): string => {
  const hue = features.valence * 60 + features.energy * 30; // Yellow-ish for happy/energetic
  const saturation = 70 + features.danceability * 30;
  const lightness = 50 + features.valence * 20;
  return `hsl(${hue}, ${saturation}%, ${lightness}%)`;
};
