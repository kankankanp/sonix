// 騰落率から色を計算
export const getChangeColor = (change: number): string => {
  if (change > 3) return '#22c55e';      // 強い上昇: 緑
  if (change > 1) return '#86efac';      // 上昇: ライトグリーン
  if (change > 0) return '#bbf7d0';      // 微上昇: 薄緑
  if (change > -1) return '#fef08a';     // 微下落: 黄
  if (change > -3) return '#fca5a5';     // 下落: ライトレッド
  return '#ef4444';                       // 強い下落: 赤
};

// 時価総額からサイズを計算（正規化）
export const getMarketCapSize = (marketCap: number): number => {
  const maxCap = Math.max(...mockCompanies.map(c => c.marketCap));
  const minSize = 0.3;
  const maxSize = 2.0;
  const normalized = Math.sqrt(marketCap / maxCap); // 平方根で差を縮める
  return minSize + normalized * (maxSize - minSize);
};

// 出来高から輝度を計算
export const getVolumeIntensity = (volume: number): number => {
  return 0.3 + volume * 0.7; // 0.3 ~ 1.0
};
